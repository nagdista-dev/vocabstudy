#!/usr/bin/env python3
"""Build the app: one page and the offline cache list.

    python3 tools/build.py            # build in place (open index.html)
    python3 tools/build.py --site     # also collect the publishable app in _site/

Writes (generated — never edit by hand):
    index.html       the whole app (every screen lives inside it)
    sw.js            the offline cache list for the installed app

The app ships with no words: every learner builds their own library in the
app, and it stays on their device. Then it runs tools/check.py.
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TEMPLATE = ROOT / "tools" / "templates" / "page.html"

# Load order matters: each file may use what the files before it define.
STYLES = [
    "assets/css/fonts.css",          # self-hosted fonts (tools/vendor.py): no font server
    "assets/css/tokens.css",
    "assets/css/base.css",
    "assets/css/components.css",
    "assets/css/views/home.css",
    "assets/css/views/library.css",
    "assets/css/views/activities.css",
    "assets/css/views/stats.css",
    "assets/css/views/print.css",
    "assets/css/views/import.css",
    "assets/css/views/data.css",
    "assets/css/motion.css",
    "assets/css/glass.css",         # the tenth accent: Liquid Glass material
]
SCRIPTS = [
    "assets/js/core/vs.js",          # must come first: defines VS.addWords
    "assets/js/core/word-forms.js",
    "assets/js/core/icons.js",
    "assets/js/core/store.js",
    "assets/js/core/speech.js",
    "assets/js/core/listen.js",
    "assets/js/core/sfx.js",
    "assets/js/core/practice.js",
    "assets/js/core/filters.js",
    "assets/js/core/sound-traps.js",
    "assets/js/core/usage-traps.js",   # the mistakes Arab learners make with a word (hand-written)
    "assets/js/core/frequency.js",     # how common a word is (list in assets/data, loaded after start-up)
    "assets/js/core/study-time.js",
    "assets/js/core/week.js",          # the Saturday–Friday week and milestones
    "assets/js/core/importer.js",
    "assets/js/core/autofill.js",
    "assets/js/core/grammar.js",       # grammar check for Use it (LanguageTool, online, optional)
    "assets/js/views/shared.js",
    "assets/js/views/home.js",
    "assets/js/views/cards.js",
    "assets/js/views/recall.js",
    "assets/js/views/quiz.js",
    "assets/js/views/spell.js",
    "assets/js/views/match.js",
    "assets/js/views/speak.js",
    "assets/js/views/write.js",
    "assets/js/views/library.js",
    "assets/js/views/stats.js",
    "assets/js/views/week.js",
    "assets/js/views/print.js",
    "assets/js/views/import.js",
    "assets/js/views/data.js",
    "assets/js/views/transfer.js",
    "assets/js/app.js",
]
NOTE = "Generated by tools/build.py. Do not edit."


def version(path: str) -> str:
    """Cache-buster from the file's modification time: browsers reload changed files."""
    return format(int((ROOT / path).stat().st_mtime), "x")


def render(root: str, title: str, description: str, body_attrs: str) -> str:
    styles = "\n".join(f'<link rel="stylesheet" href="{root}{p}?v={version(p)}">' for p in STYLES)
    scripts = "\n".join(f'<script src="{root}{p}?v={version(p)}"></script>' for p in SCRIPTS)
    page = TEMPLATE.read_text(encoding="utf-8")
    for key, value in {
        "{{ROOT}}": root, "{{TITLE}}": title, "{{DESCRIPTION}}": description,
        "{{BODY_ATTRS}}": body_attrs, "{{STYLES}}": styles, "{{SCRIPTS}}": scripts,
        "{{GENERATED_NOTE}}": NOTE + " Template: tools/templates/page.html",
    }.items():
        page = page.replace(key, value)
    if "{{" in page:
        raise SystemExit("template has an unknown {{placeholder}}")
    return page


# Everything the published app needs — and nothing else (no tools, no docs).
SITE_FILES = ["index.html", "about.html", "sw.js", "manifest.webmanifest", ".nojekyll", "CNAME"]   # CNAME: pins the GitHub Pages custom domain (vocabstudy.nagdista.com)
SITE_DIRS = ["assets"]


def collect_site() -> None:
    """Copy the publishable app into _site/ (used by .github/workflows/pages.yml)."""
    import shutil
    site = ROOT / "_site"
    shutil.rmtree(site, ignore_errors=True)
    for rel in SITE_FILES:
        (site / rel).parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(ROOT / rel, site / rel)
    for rel in SITE_DIRS:
        shutil.copytree(ROOT / rel, site / rel)
    count = sum(1 for p in site.rglob("*") if p.is_file())
    print(f"site ready in _site/ · {count} files")


def write_service_worker() -> None:
    """sw.js lists every file the app needs offline, with the same ?v= URLs the pages use."""
    import hashlib
    import json
    files = ["index.html", "manifest.webmanifest", "assets/favicon.svg",
             "assets/icons/icon-192.png", "assets/icons/icon-512.png",
             "assets/icons/maskable-512.png", "assets/icons/apple-touch-icon.png"]
    files += [f"{p}?v={version(p)}" for p in STYLES + SCRIPTS]
    # Fonts and the PDF maker live in the project too, so everything works offline.
    files += sorted(str(p.relative_to(ROOT)) for p in (ROOT / "assets" / "fonts").glob("*.woff2"))
    files += ["assets/vendor/html2pdf.bundle.min.js", "assets/vendor/qrcode.js", "assets/vendor/jsQR.js",
              "assets/data/frequency.js"]
    stamp = hashlib.sha1("|".join(files).encode()).hexdigest()[:10]
    sw = (ROOT / "tools" / "templates" / "sw.js").read_text(encoding="utf-8")
    sw = sw.replace("{{VERSION}}", stamp).replace("{{PRECACHE}}", json.dumps(files, indent=2))
    (ROOT / "sw.js").write_text(sw, encoding="utf-8")




def main() -> int:
    (ROOT / "index.html").write_text(
        render("", "VocabStudy — vocabulary with spaced recall",
               "Free app for Arabic speakers learning English: add your words, then recall them on spaced days so they stick.", ""),
        encoding="utf-8")
    write_service_worker()
    if "--site" in sys.argv:
        collect_site()
    print("built index.html and sw.js")
    return subprocess.run([sys.executable, str(ROOT / "tools" / "check.py")]).returncode


if __name__ == "__main__":
    sys.exit(main())
