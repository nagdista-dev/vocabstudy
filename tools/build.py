#!/usr/bin/env python3
"""Build the app: one page, plus the Starter set and the offline cache list.

    python3 tools/build.py

Writes (generated — never edit by hand):
    index.html       the whole app (every screen lives inside it)
    data/words.js    the Starter set from data/sample/*.js
    sw.js            the offline cache list for the installed app

Learners add their own words inside the app (Add words): typed one by one,
pasted from a spreadsheet, or uploaded as files. Those words stay on their
device; nothing personal is ever part of the build.

It runs tools/check.py first and stops if the sample data has errors.
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TEMPLATE = ROOT / "tools" / "templates" / "page.html"
SAMPLE = ROOT / "data" / "sample"     # the Starter set that ships with the app


def data_dir() -> Path:
    """Where the built-in words come from: only the Starter set."""
    return SAMPLE


DATA = data_dir()
BUNDLE = ROOT / "data" / "words.js"

# Load order matters: each file may use what the files before it define.
STYLES = [
    "assets/css/tokens.css",
    "assets/css/base.css",
    "assets/css/components.css",
    "assets/css/views/home.css",
    "assets/css/views/day.css",
    "assets/css/views/activities.css",
    "assets/css/views/stats.css",
    "assets/css/views/print.css",
    "assets/css/views/import.css",
    "assets/css/views/data.css",
    "assets/css/motion.css",
]
SCRIPTS = [
    "assets/js/core/vs.js",          # must come first: defines VS.addDay
    "data/words.js",                 # the words (generated)
    "assets/js/core/word-forms.js",
    "assets/js/core/icons.js",
    "assets/js/core/store.js",
    "assets/js/core/speech.js",
    "assets/js/core/sfx.js",
    "assets/js/core/practice.js",
    "assets/js/core/study-time.js",
    "assets/js/core/importer.js",
    "assets/js/views/shared.js",
    "assets/js/views/word-browser.js",
    "assets/js/views/home.js",
    "assets/js/views/day.js",
    "assets/js/views/cards.js",
    "assets/js/views/recall.js",
    "assets/js/views/quiz.js",
    "assets/js/views/spell.js",
    "assets/js/views/match.js",
    "assets/js/views/library.js",
    "assets/js/views/stats.js",
    "assets/js/views/print.js",
    "assets/js/views/import.js",
    "assets/js/views/data.js",
    "assets/js/app.js",
]
NOTE = "Generated by tools/build.py. Do not edit."


def bundle(days: list[Path]) -> None:
    parts = [f"/* {NOTE} Source: data/days/*.js */\n"]
    for d in days:
        parts.append(f"\n/* ── {d.name} ── */\n" + d.read_text(encoding="utf-8").strip() + "\n")
    BUNDLE.write_text("".join(parts), encoding="utf-8")


def version(path: str) -> str:
    """Cache-buster from the file's modification time: browsers reload changed files."""
    return format(int((ROOT / path).stat().st_mtime), "x")


def render(root: str, title: str, description: str, body_attrs: str) -> str:
    styles = "\n".join(f'<link rel="stylesheet" href="{root}{p}?v={version(p)}">' for p in STYLES)
    scripts = "\n".join(f'<script src="{root}{p}?v={version(p)}"></script>' for p in SCRIPTS)
    page = TEMPLATE.read_text(encoding="utf-8")
    for key, value in {
        "{{ROOT}}": root, "{{TITLE}}": title, "{{DESCRIPTION}}": description,
        "{{BODY_ATTRS}}": body_attrs, "{{STYLES}}": styles, "{{SCRIPTS}}": scripts,
        "{{GENERATED_NOTE}}": NOTE + " Template: tools/templates/page.html",
    }.items():
        page = page.replace(key, value)
    if "{{" in page:
        raise SystemExit("template has an unknown {{placeholder}}")
    return page


def write_service_worker() -> None:
    """sw.js lists every file the app needs offline, with the same ?v= URLs the pages use."""
    import hashlib
    import json
    files = ["index.html", "manifest.webmanifest", "assets/favicon.svg",
             "assets/icons/icon-192.png", "assets/icons/icon-512.png",
             "assets/icons/maskable-512.png", "assets/icons/apple-touch-icon.png"]
    files += [f"{p}?v={version(p)}" for p in STYLES + SCRIPTS]
    stamp = hashlib.sha1("|".join(files).encode()).hexdigest()[:10]
    sw = (ROOT / "tools" / "templates" / "sw.js").read_text(encoding="utf-8")
    sw = sw.replace("{{VERSION}}", stamp).replace("{{PRECACHE}}", json.dumps(files, indent=2))
    (ROOT / "sw.js").write_text(sw, encoding="utf-8")




def main() -> int:
    check = subprocess.run([sys.executable, str(ROOT / "tools" / "check.py"), "--data-only", "--quiet"])
    if check.returncode:
        print("build stopped: fix the errors above, then run it again.")
        return 1

    days = sorted(DATA.glob("*.js"))
    bundle(days)
    (ROOT / "index.html").write_text(
        render("", "VocabStudy — vocabulary with spaced recall",
               "Free app for Arabic speakers learning English: add your words, then recall them on spaced days so they stick.", ""),
        encoding="utf-8")
    old_days = ROOT / "days"                       # pages from older versions: no longer used
    if old_days.is_dir():
        for page in old_days.glob("*.html"):
            page.unlink()
        if not any(old_days.iterdir()):
            old_days.rmdir()
    write_service_worker()
    words = BUNDLE.read_text(encoding="utf-8").count("{ word:")
    print(f"built index.html · {words} Starter words from {DATA.relative_to(ROOT)}/")
    return 0


if __name__ == "__main__":
    sys.exit(main())
