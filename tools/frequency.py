#!/usr/bin/env python3
"""Write the word-frequency list the app ships with: "how common is this word?"

    python3 -m venv /tmp/wf && /tmp/wf/bin/pip install wordfreq
    /tmp/wf/bin/python tools/frequency.py

Writes assets/data/frequency.js — the 30,000 most used English words, most
common first, as one string. The app reads a word's rank from it (taking the
best rank of the word's forms: borrow, borrowed, borrowing…) and shows the
learner whether it's one of the 1,000 most used words or a rare one, so time
goes to the words that pay off. Nothing is looked up online.

Source: wordfreq by Robyn Speer (https://github.com/rspeer/wordfreq) — English
frequencies combined from subtitles, books, Wikipedia, news and the web.
Its data is licensed CC BY-SA 4.0, so the generated file is too (see its header).
Run this by hand when the list should change, and commit the result;
tools/build.py never touches the network or needs wordfreq.
"""

from __future__ import annotations

import re
from pathlib import Path

from wordfreq import top_n_list  # type: ignore

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "assets" / "data" / "frequency.js"
KEEP = 30000
WORD = re.compile(r"[a-z][a-z'-]*[a-z]|[ai]")    # real words: no numbers, "e.g", "u.s", "°"

HEADER = """/* assets/data/frequency.js — generated by tools/frequency.py. Do not edit.
   The {n:,} most used English words, most common first (VS.frequency reads it).
   Data: wordfreq by Robyn Speer, https://github.com/rspeer/wordfreq
   Licence: Creative Commons Attribution-ShareAlike 4.0 (CC BY-SA 4.0),
   https://creativecommons.org/licenses/by-sa/4.0/ — this file is shared under the same licence. */
"""


def main() -> None:
    words: list[str] = []
    for w in top_n_list("en", 45000):
        if WORD.fullmatch(w) and w not in words:
            words.append(w)
        if len(words) == KEEP:
            break
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(HEADER.format(n=len(words)) + 'window.VS_FREQ = "' + " ".join(words) + '";\n', encoding="utf-8")
    print(f"frequency: {len(words):,} words, {OUT.stat().st_size // 1024} KB → {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
